let lang = 'es';

export const LANGUAGES = [
  { value: 'es', label: 'Español' },
  { value: 'en', label: 'English' },
];

export function setLanguage(next) {
  lang = DICT[next] ? next : 'es';
  document.documentElement.lang = lang;
  translateDom();
  return lang;
}

export const getLanguage = () => lang;

export function t(key, vars) {
  const value = DICT[lang][key] ?? DICT.es[key] ?? key;
  if (typeof value !== 'string') return value;
  return vars ? value.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match)) : value;
}

// Traducción de etiquetas que vienen del servidor (estilos, resoluciones, modelos).
// En español se conserva exactamente el texto del servidor.
export function tl(group, id, fallback) {
  const value = DICT[lang][`${group}.${id}`];
  return typeof value === 'string' ? value : fallback;
}

export const ideas = () => DICT[lang].ideas ?? DICT.es.ideas;

export function translateDom(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) {
    node.setAttribute('placeholder', t(node.dataset.i18nPlaceholder));
  }
  for (const node of root.querySelectorAll('[data-i18n-aria]')) {
    node.setAttribute('aria-label', t(node.dataset.i18nAria));
  }
}
